<?php
// app/Helpers/SettingHelper.php
require_once dirname(__DIR__, 2) . '/config/database.php';
require_once __DIR__ . '/LogHelper.php';

class SettingHelper {
    private static ?array $cache = null;

    public static function getAll(): array {
        if (self::$cache === null) {
            try {
                $pdo = Database::getConnection();
                $rows = $pdo->query("SELECT setting_key, setting_value FROM app_settings")->fetchAll();
                self::$cache = [];
                foreach ($rows as $r) {
                    self::$cache[$r['setting_key']] = $r['setting_value'];
                }
            } catch (Exception $e) {
                self::$cache = [];
            }
        }
        return self::$cache;
    }

    public static function get(string $key, ?string $default = null): ?string {
        $all = self::getAll();
        if (isset($all[$key]) && $all[$key] !== '') {
            return $all[$key];
        }
        return $default;
    }

    public static function set(string $key, ?string $value): void {
        $pdo = Database::getConnection();
        $stmt = $pdo->prepare("REPLACE INTO app_settings (setting_key, setting_value, updated_at) VALUES (:k, :v, NOW())");
        $stmt->execute([':k' => $key, ':v' => $value]);
        if (self::$cache !== null) {
            self::$cache[$key] = $value;
        }
    }

    public static function setMultiple(array $data): void {
        $pdo = Database::getConnection();
        $stmt = $pdo->prepare("REPLACE INTO app_settings (setting_key, setting_value, updated_at) VALUES (:k, :v, NOW())");
        foreach ($data as $k => $v) {
            $stmt->execute([':k' => $k, ':v' => (string)$v]);
            if (self::$cache !== null) {
                self::$cache[$k] = (string)$v;
            }
        }
    }

    public static function getLogoUrl(): string {
        $logo = self::get('logo_url');
        if (!empty($logo)) {
            $cleanPath = ltrim($logo, '/');
            // If it's a relative path in public/
            if (file_exists(PUBLIC_PATH . '/' . $cleanPath)) {
                return asset($cleanPath);
            }
        }

        // Check fallback existing files
        if (file_exists(PUBLIC_PATH . '/uploads/settings/logo.png')) {
            return asset('uploads/settings/logo.png');
        }
        if (file_exists(PUBLIC_PATH . '/assets/images/logo.png')) {
            return asset('assets/images/logo.png');
        }

        return asset('assets/images/logo-placeholder.svg');
    }

    public static function uploadLogo(array $file): array {
        if (empty($file['tmp_name']) || !is_uploaded_file($file['tmp_name'])) {
            return ['success' => false, 'error' => 'File logo tidak valid atau tidak diunggah dengan benar.'];
        }

        $maxSize = 3 * 1024 * 1024; // 3MB
        if ($file['size'] > $maxSize) {
            return ['success' => false, 'error' => 'Ukuran file logo maksimal 3MB.'];
        }

        $ext = strtolower(pathinfo($file['name'], PATHINFO_EXTENSION));
        $allowedExts = ['png', 'jpg', 'jpeg', 'webp', 'svg'];
        if (!in_array($ext, $allowedExts, true)) {
            return ['success' => false, 'error' => 'Format logo harus berupa PNG, JPG, JPEG, WEBP, atau SVG.'];
        }

        // Additional MIME check for safety
        $finfo = finfo_open(FILEINFO_MIME_TYPE);
        $mime = finfo_file($finfo, $file['tmp_name']);
        finfo_close($finfo);

        $allowedMimes = ['image/png', 'image/jpeg', 'image/webp', 'image/svg+xml', 'image/x-svg', 'text/plain', 'text/html'];
        if (!in_array($mime, $allowedMimes, true) && $ext !== 'svg') {
            return ['success' => false, 'error' => 'Tipe file gambar tidak diizinkan.'];
        }

        $targetDir = PUBLIC_PATH . '/uploads/settings';
        if (!is_dir($targetDir)) {
            mkdir($targetDir, 0777, true);
        }

        $fileName = 'school_logo_' . time() . '.' . $ext;
        $dest = $targetDir . '/' . $fileName;

        if (!move_uploaded_file($file['tmp_name'], $dest)) {
            return ['success' => false, 'error' => 'Gagal memindahkan file logo yang diunggah ke server.'];
        }

        $relativePath = 'uploads/settings/' . $fileName;
        self::set('logo_url', $relativePath);

        // Optional base64 square PNG generated by browser canvas (supports WEBP/SVG/PNG/JPG)
        $canvasPngPath = null;
        if (!empty($_POST['favicon_png_base64']) && strpos($_POST['favicon_png_base64'], 'data:image/png;base64,') === 0) {
            $rawPng = base64_decode(substr($_POST['favicon_png_base64'], strlen('data:image/png;base64,')));
            if ($rawPng !== false && strlen($rawPng) > 64) {
                $canvasPngPath = $targetDir . '/_canvas_source.png';
                file_put_contents($canvasPngPath, $rawPng);
            }
        }

        self::syncFavicons($canvasPngPath ?: $dest);
        if ($canvasPngPath && file_exists($canvasPngPath)) {
            @unlink($canvasPngPath);
        }

        LogHelper::log('LOGO_UPDATED', "Admin mengunggah logo baru sekolah/aplikasi: {$fileName}");

        return ['success' => true, 'path' => $relativePath, 'url' => asset($relativePath)];
    }

    public static function resetLogo(): bool {
        self::set('logo_url', 'assets/images/logo-placeholder.svg');
        $defaultPngSource = PUBLIC_PATH . '/assets/images/logo-placeholder-source.png';
        self::syncFavicons(file_exists($defaultPngSource) ? $defaultPngSource : null);
        LogHelper::log('LOGO_RESET', "Admin mereset logo ke logo default.");
        return true;
    }

    /**
     * Generate square PNG favicons (16x16, 32x32, 48x48, 64x64) and a multi-frame .ico file
     * so browsers persist the icon in their Favicon DB without flashing XAMPP's default icon on reload.
     */
    public static function syncFavicons(?string $sourceImagePath = null): bool {
        $targetDir = PUBLIC_PATH . '/uploads/settings';
        if (!is_dir($targetDir)) {
            @mkdir($targetDir, 0777, true);
        }

        if ($sourceImagePath === null) {
            $logo = self::get('logo_url');
            if (!empty($logo)) {
                $candidate = PUBLIC_PATH . '/' . ltrim($logo, '/');
                if (file_exists($candidate)) {
                    $sourceImagePath = $candidate;
                }
            }
        }

        if ($sourceImagePath && strtolower(pathinfo($sourceImagePath, PATHINFO_EXTENSION)) === 'svg') {
            $fallbackSource = PUBLIC_PATH . '/assets/images/logo-placeholder-source.png';
            if (file_exists($fallbackSource)) {
                $sourceImagePath = $fallbackSource;
            }
        }

        if (!$sourceImagePath || !file_exists($sourceImagePath)) {
            return false;
        }

        $sizes = [16, 32, 48, 64];
        $generatedPngs = [];

        // Use Windows .NET System.Drawing via PowerShell to render crisp square PNGs
        $srcEscaped = str_replace("'", "''", $sourceImagePath);
        $dirEscaped = str_replace("'", "''", $targetDir);
        $psScript = "
            \$ErrorActionPreference = 'Stop';
            Add-Type -AssemblyName System.Drawing;
            \$srcImg = [System.Drawing.Image]::FromFile('$srcEscaped');
            foreach (\$s in @(16, 32, 48, 64)) {
                \$bmp = New-Object System.Drawing.Bitmap(\$s, \$s, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb);
                \$g = [System.Drawing.Graphics]::FromImage(\$bmp);
                \$g.Clear([System.Drawing.Color]::Transparent);
                \$g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic;
                \$g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality;
                \$g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality;
                \$ratio = [Math]::Min(\$s / \$srcImg.Width, \$s / \$srcImg.Height);
                \$w = [int][Math]::Round(\$srcImg.Width * \$ratio);
                \$h = [int][Math]::Round(\$srcImg.Height * \$ratio);
                \$x = [int][Math]::Floor((\$s - \$w) / 2);
                \$y = [int][Math]::Floor((\$s - \$h) / 2);
                \$g.DrawImage(\$srcImg, \$x, \$y, \$w, \$h);
                \$g.Dispose();
                \$outPath = Join-Path '$dirEscaped' ('favicon-' + \$s + 'x' + \$s + '.png');
                \$bmp.Save(\$outPath, [System.Drawing.Imaging.ImageFormat]::Png);
                \$bmp.Dispose();
            }
            \$srcImg.Dispose();
        ";

        $encodedCmd = base64_encode(mb_convert_encoding($psScript, 'UTF-16LE', 'UTF-8'));
        @exec("powershell -NoProfile -NonInteractive -EncodedCommand {$encodedCmd} 2>&1", $out, $code);

        foreach ($sizes as $s) {
            $pngFile = $targetDir . "/favicon-{$s}x{$s}.png";
            if (file_exists($pngFile) && filesize($pngFile) > 0) {
                $generatedPngs[$s] = $pngFile;
            }
        }

        if (!empty($generatedPngs)) {
            $icoFrames = [];
            foreach ([16, 32, 48] as $icoSize) {
                if (isset($generatedPngs[$icoSize])) {
                    $icoFrames[$icoSize] = file_get_contents($generatedPngs[$icoSize]);
                }
            }
            if (!empty($icoFrames)) {
                $icoBinary = self::packMultiFrameIco($icoFrames);
                file_put_contents($targetDir . '/favicon.ico', $icoBinary);
                @file_put_contents(PUBLIC_PATH . '/favicon.ico', $icoBinary);
                @file_put_contents(BASE_PATH . '/favicon.ico', $icoBinary);
            }
            return true;
        }

        return false;
    }

    /**
     * Pack multiple square PNG images (e.g. 16x16, 32x32, 48x48) into a standard Windows .ico binary.
     */
    private static function packMultiFrameIco(array $framesBySize): string {
        $count = count($framesBySize);
        $header = pack('vvv', 0, 1, $count);
        $offset = 6 + ($count * 16);
        $dirEntries = '';
        $imageData = '';

        foreach ($framesBySize as $size => $pngBytes) {
            $dim = ($size >= 256) ? 0 : $size;
            $len = strlen($pngBytes);
            $dirEntries .= pack('CCCCvvVV', $dim, $dim, 0, 0, 1, 32, $len, $offset);
            $imageData .= $pngBytes;
            $offset += $len;
        }

        return $header . $dirEntries . $imageData;
    }

    /**
     * Get standardized square favicon URLs with cache-busting tied to the file modification time.
     */
    public static function getFaviconData(): array {
        $targetDir = PUBLIC_PATH . '/uploads/settings';
        $icoFile = $targetDir . '/favicon.ico';
        $png32File = $targetDir . '/favicon-32x32.png';
        $png64File = $targetDir . '/favicon-64x64.png';

        if (!file_exists($icoFile) || !file_exists($png32File)) {
            self::syncFavicons();
        }

        if (file_exists($icoFile) && file_exists($png32File)) {
            $ver = filemtime($icoFile);
            return [
                'ico'   => asset('uploads/settings/favicon.ico') . '?v=' . $ver,
                'png16' => asset('uploads/settings/favicon-16x16.png') . '?v=' . $ver,
                'png32' => asset('uploads/settings/favicon-32x32.png') . '?v=' . $ver,
                'png64' => asset('uploads/settings/favicon-64x64.png') . '?v=' . $ver,
                'type'  => 'image/png',
            ];
        }

        $fallbackUrl = self::getLogoUrl();
        return [
            'ico'   => $fallbackUrl,
            'png16' => $fallbackUrl,
            'png32' => $fallbackUrl,
            'png64' => $fallbackUrl,
            'type'  => 'image/png',
        ];
    }
}
